begin;

do $guard$ begin
  if to_regclass('public.community') is null or to_regclass('public.event_attendees') is not null then
    raise exception 'WRONG PROJECT: this file is for BUILDSPACE (mqbsjlgnsirqsmfnreqd). Nothing was changed.';
  end if;
end $guard$;

alter table public.zork_saves add column if not exists save_key_hash text;
create unique index if not exists zork_saves_save_key_hash_idx on public.zork_saves (save_key_hash);

-- p_key: 64 hex characters generated by the browser (32 random bytes).
create or replace function public.zork_save(p_key text, p_data text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare v_hash text;
begin
  if p_key is null or p_key !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid save key' using errcode = '22023';
  end if;
  if p_data is null or length(p_data) = 0 or length(p_data) > 262144 then
    raise exception 'invalid save data' using errcode = '22023';
  end if;
  v_hash := encode(sha256(convert_to(p_key, 'UTF8')), 'hex');
  insert into public.zork_saves (username, save_key_hash, save_data, updated_at)
  values ('key:' || v_hash, v_hash, p_data, now())
  on conflict (save_key_hash) do update
    set save_data = excluded.save_data, updated_at = now();
end;
$$;

create or replace function public.zork_load(p_key text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_key is null or p_key !~ '^[0-9a-f]{64}$' then
    return null;
  end if;
  return (select s.save_data from public.zork_saves s
          where s.save_key_hash = encode(sha256(convert_to(p_key, 'UTF8')), 'hex'));
end;
$$;

revoke all on function public.zork_save(text, text) from public;
revoke all on function public.zork_load(text) from public;
grant execute on function public.zork_save(text, text) to anon, authenticated;
grant execute on function public.zork_load(text) to anon, authenticated;

commit;
